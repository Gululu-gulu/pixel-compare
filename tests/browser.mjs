import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, copyFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scratch = path.join(project, 'work', `browser-test-${Date.now()}`);
const dataset = path.join(scratch, 'dataset');
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [], external = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (!/^(http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\/|blob:|data:)/.test(request.url())) external.push(request.url()); });
await page.addInitScript(() => {
  const active = new Set();
  window.__activeObjectURLs = active;
  const create = URL.createObjectURL.bind(URL), revoke = URL.revokeObjectURL.bind(URL);
  URL.createObjectURL = blob => { const url = create(blob); active.add(url); return url; };
  URL.revokeObjectURL = url => { active.delete(url); revoke(url); };
});
const check = (description) => console.log(`✓ ${description}`);
const ready = () => page.getByText('共用坐标变换', { exact: true }).waitFor();
const clickRow = name => page.locator('.pair-row').filter({ has: page.locator('b', { hasText: new RegExp(`^${name}$`) }) }).click();
const canvasHash = (target = page) => target.locator('canvas').evaluate(canvas => {
  const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
  let hash = 2166136261;
  for (let i = 0; i < data.length; i++) hash = Math.imul(hash ^ data[i], 16777619);
  return hash >>> 0;
});
const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
const moveSplit = async percentage => {
  const stage = await page.locator('.stage').boundingBox(), handle = await page.locator('.divider-handle').boundingBox();
  const grabX = Math.max(stage.x + 3, Math.min(stage.x + stage.width - 3, handle.x + handle.width / 2));
  await page.mouse.move(grabX, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(stage.x + stage.width * percentage, stage.y + stage.height / 2, { steps: 6 });
  await page.mouse.up();
  await page.mouse.move(20, 20);
  await frame();
  const split = Number(await page.getByRole('slider', { name: '左右图像分割线' }).getAttribute('aria-valuenow'));
  assert.ok(Math.abs(split - Math.max(0, Math.min(100, Math.round(percentage * 100)))) <= 1, `divider did not move to ${percentage}: ${split}`);
};

